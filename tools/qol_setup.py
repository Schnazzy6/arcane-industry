"""Configure the QoL expansion and gate automation through existing MI/magic parts."""
import json,zipfile,copy,shutil
from qol_expansion import ROOT,CLIENT,SERVER,LOCAL

rows=json.loads((ROOT/'build/qol-expansion.json').read_text('utf-8'))
(ROOT/'qol.lock.json').write_text(json.dumps(rows,ensure_ascii=False,indent=2),'utf-8')
by_slug={r['slug']:r for r in rows}
patches=[]
def gate(slug,name,component):
 with zipfile.ZipFile(ROOT/'cache/files'/by_slug[slug]['filename']) as z:
  path=next(n for n in z.namelist() if '/recipe/' in n and n.endswith('/'+name+'.json'))
  recipe=json.loads(z.read(path))
 rid=path.split('/')[1]+':'+path.split('/recipe/')[1][:-5]
 assert recipe['type']=='minecraft:crafting_shaped',rid
 pattern=[list(s) for s in recipe['pattern']]
 # Keep the original central ingredient; replace one peripheral slot with a gate.
 y,x=next((y,x) for y,row in enumerate(pattern) for x,ch in enumerate(row) if ch!=' ' and (y,x)!=(1,1))
 pattern[y][x]='@';recipe['pattern']=[''.join(s) for s in pattern]
 used=set(''.join(recipe['pattern']))
 recipe['key']={k:v for k,v in recipe['key'].items() if k in used}
 recipe['key']['@']={'item':'kubejs:'+component}
 patches.append({'id':rid,'json':recipe})

for name in ['gadget_building','gadget_exchanging']:
 gate('building-gadgets',name,'electrical_focus')
for name in ['gadget_copy_paste','gadget_cut_paste','gadget_destruction']:
 gate('building-gadgets',name,'industrial_focus')
for name in ['recipe_fan','recipe_absorption_hopper']:
 gate('mob-grinding-utils',name,'electrical_focus')
for name in ['recipe_saw','recipe_cursed_feed','recipe_nutritious_feed']:
 gate('mob-grinding-utils',name,'industrial_focus')
gate('mob-grinding-utils','recipe_entity_spawner','ritual_frame')
gate('modular-routers','modular_router','electrical_focus')
for name in ['player_module','activator_module']:
 gate('modular-routers',name,'industrial_focus')

script='// Generated by tools/qol_setup.py; retain native recipe IDs.\nServerEvents.recipes(event => {\n'
for p in patches:
 script+='  event.remove({id:'+json.dumps(p['id'])+'});\n  event.custom('+json.dumps(p['json'],separators=(',',':'))+').id('+json.dumps(p['id'])+');\n'
script+='});\n'
rel='kubejs/server_scripts/qol_progression.js'
for base in [ROOT/'overrides/common',CLIENT,SERVER,LOCAL]:
 p=base/rel;p.parent.mkdir(parents=True,exist_ok=True);p.write_text(script,'utf-8')

backup='''# Full world backups every 60 minutes; bounded retention.
enabled = true
backupType = "FULL_BACKUPS"
saveAll = true
timer = 60
backupsToKeep = 12
compressionLevel = 1
maxDiskSize = "20 GB"
outputPath = "simplebackups"
noPlayerBackups = false
'''
for base in [ROOT/'overrides/server',SERVER]:
 p=base/'config/simplebackups-common.toml';p.parent.mkdir(parents=True,exist_ok=True);p.write_text(backup,'utf-8')
for base in [ROOT/'overrides/client',CLIENT,LOCAL]:
 p=base/'config/moreoverlays.toml';p.parent.mkdir(parents=True,exist_ok=True)
 p.write_text('[searchoverlay]\nsearch_enabled = false\n','utf-8')
# F7 already opens Iris settings. Move just that shortcut, keeping light overlay on F7.
for base in [CLIENT,LOCAL]:
 p=base/'options.txt'
 if p.exists():
  lines=p.read_text('utf-8').splitlines()
  updates={'key_iris.keybind.shaderPackSelection':'key.keyboard.unknown','key_key.moreoverlays.lightoverlay.desc':'key.keyboard.f7','key_key.moreoverlays.chunkbounds.desc':'key.keyboard.f9'}
  lines=[s for s in lines if s.split(':',1)[0] not in updates]
  lines += [k+':'+v for k,v in updates.items()]
  p.write_text('\n'.join(lines)+'\n','utf-8')
(ROOT/'build/qol-recipe-patches.json').write_text(json.dumps(patches,ensure_ascii=False,indent=2),'utf-8')
print('Configured backups and overlays;',len(patches),'native recipe gates; no launch.')
if (ROOT/'tools/progression_security.py').exists():
 from progression_security import generate
 generate()
